/* The dialogue's canonical home is the text-only page of each game. Extract it
   rather than retyping it: a second hand-typed copy is exactly how two
   versions drift apart.
     node extract-text.mjs       Before the Law     -> src/text.gen.js
     node extract-text.mjs im    An Imperial Message -> src/im/text.gen.js */
import fs from 'fs';
const GAMES = {
  btl: { html: '../before-the-law.html', out: '../src/text.gen.js' },
  im: { html: '../imperial-message.html', out: '../src/im/text.gen.js' },
};
const id = process.argv[2] || 'btl';
const G = GAMES[id];
if (!G) throw new Error('unknown game ' + id);
const src = fs.readFileSync(G.html, 'utf8');
const a = src.indexOf('var T = {');
const b = src.indexOf('\n};', a);
if (a < 0 || b < 0) throw new Error('could not locate the T block in ' + G.html);
const block = src.slice(a + 'var T = '.length, b + 3).replace(/;\s*$/, '');
fs.mkdirSync(G.out.replace(/\/[^/]+$/, ''), { recursive: true });
fs.writeFileSync(G.out,
  `/* generated by tools/extract-text.mjs from ${G.html.replace('../', '')} - do not edit */\nexport const T = ` + block + ';\n');
const T = (await import(G.out + '?' + Date.now())).T;
const keys = Object.keys(T);
console.log('extracted', keys.length, 'blocks:', keys.join(' '));
let n = 0; for (const k of keys) if (k[0] !== '_') n += Array.isArray(T[k][0]) ? T[k].flat().length : T[k].length;
console.log('total spoken lines:', n);
