/* Builds the 3D "An Imperial Message" into one self-contained file,
   ../imperial-message-3d.html, that opens by double-click with no network.
     1. text:   imperial-message.html's T block -> src/im/text.gen.js
     2. voice:  assets/voice-im/<hash>.mp3      -> src/im/voice.gen.js
     3. models: assets/models/im/game/*.glb      -> src/im/models.gen.js
     4. bundle: src/im/game.js (+ three) into the page shell below.
   Usage: node build-im.mjs */
