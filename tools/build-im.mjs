/* ---- voice: only lines still in the text are inlined ---- */
{
  const hashLine = s => { let h = 0x811c9dc5; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); } return (h >>> 0).toString(16).padStart(8, '0'); };
  const lines = [];
  const walk = v => typeof v === 'string' ? lines.push(v) : Array.isArray(v) ? v.forEach(walk) : 0;
  for (const [k, v] of Object.entries(T)) if (k[0] !== '_') walk(v);
  const V = {}; let missing = 0;
  for (const l of lines) {
    const h = hashLine(l), f = '../assets/voice-im/' + h + '.mp3';
    if (fs.existsSync(f)) V[h] = 'data:audio/mpeg;base64,' + fs.readFileSync(f).toString('base64'); else missing++;
  }
  fs.writeFileSync('../src/im/voice.gen.js', '/* generated by tools/build-im.mjs from assets/voice-im - do not edit */\nexport const VOICE = ' + JSON.stringify(V) + ';\n');
  console.log('voice: ' + Object.keys(V).length + ' lines inlined' + (missing ? ', ' + missing + ' unvoiced (run make-voice.mjs im)' : ''));
}

/* ---- sculpts, reduced by prep-models.mjs im ---- */
{
  const { NodeIO } = await import('@gltf-transform/core');
  const io = new NodeIO(), M = {}, dir = '../assets/models/im/game/';
  if (fs.existsSync(dir)) for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.glb'))) {
    const prim = (await io.read(dir + f)).getRoot().listMeshes()[0].listPrimitives()[0];
    const b64 = a => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString('base64');
    const idx = prim.getIndices().getArray();
    const wide = idx.reduce((m, v) => v > m ? v : m, 0) > 65535;
    M[f.replace('.glb', '')] = { pos: b64(new Float32Array(prim.getAttribute('POSITION').getArray())), idx: b64(wide ? new Uint32Array(idx) : new Uint16Array(idx)), wide };
    /* painted sculpts carry their colours, baked per vertex by import-im-models.mjs */
    const c = prim.getAttribute('COLOR_0');
    if (c) { const a = c.getArray(), n = c.getCount(), u8 = new Uint8Array(n * 3); for (let i = 0; i < n * 3; i++) u8[i] = Math.round(Math.min(1, a[i] * (c.getNormalized() ? 1 / 255 : 1)) * 255); M[f.replace('.glb', '')].col = b64(u8); }
  }
  fs.writeFileSync('../src/im/models.gen.js', '/* generated by tools/build-im.mjs from assets/models/im/game - do not edit */\nexport const MODELS = ' + JSON.stringify(M) + ';\n');
  console.log('models: ' + (Object.keys(M).join(', ') || 'none (hand-built figures)'));
}

